"""Compile per-service signal fragments → the agent's aggregated topology +
contracts (signal-plane-design backlog: ownership refactor).

ARE says ownership/criticality is the service team's schema, not a central
wiki page. So each service OWNS its declaration in
`demo-services/services/<svc>/signal.yaml` (tier, journey membership, SLIs,
logs, exclusions, and its OUTBOUND dependency edges + how it attributes each
dependency's failures). This module aggregates those fragments into the two
files the agent loads (`app/signals/topology.yaml`, `contracts.yaml`).

Mirrors how Weaver works: decentralized contributions → a compiled artifact.
The agent ships the compiled aggregates (its image has no demo-services), so the
compile step is dev/CI-time — like the Weaver alignment check. The cross-service
topology graph is the UNION of per-service outbound edges (caller-owned), and
each journey's ordered chain is DERIVED from that graph (deterministic topo-sort),
so nothing cross-service is hand-maintained.
"""

from __future__ import annotations

import heapq
import logging
from collections import defaultdict
from pathlib import Path

import yaml
from pydantic import BaseModel, Field

from ..config import settings
from .contract import SLI, ContractSet, LogSignal, SignalContract
from .topology import Edge, ServiceNode, Topology

logger = logging.getLogger("aiops_agent.signals.compile")

SIGNAL_VERSION = "1.0.0"

_GENERATED_HEADER = (
    "# GENERATED by `python -m app.signals.compile` from the per-service\n"
    "# signal fragments in demo-services/services/*/signal.yaml — DO NOT EDIT.\n"
    "# Each service owns its declaration; edit the fragment, then recompile.\n"
)


class Dependency(BaseModel):
    callee: str
    attribution: str = ""


class ServiceSignal(BaseModel):
    """One service's owned signal declaration (the fragment schema)."""
    service: str
    role: str = ""
    tier: int = 3
    journeys: list[str] = Field(default_factory=list)
    git_version: str = ""
    owner: str = ""
    freshness_seconds: int = 60
    supported_decisions: list[str] = Field(default_factory=list)
    slis: list[SLI] = Field(default_factory=list)
    logs: LogSignal | None = None
    exclusions: list[str] = Field(default_factory=list)
    depends_on: list[Dependency] = Field(default_factory=list)


def _fragments_dir() -> Path:
    if settings.signal_fragments_dir:
        return Path(settings.signal_fragments_dir)
    return Path(__file__).parents[4] / "demo-services/services"


def load_fragments(directory: Path | None = None) -> list[ServiceSignal]:
    d = directory or _fragments_dir()
    frags = [
        ServiceSignal.model_validate(yaml.safe_load(p.read_text(encoding="utf-8")) or {})
        for p in sorted(d.glob("*/signal.yaml"))
    ]
    return frags


def _topo_sort(nodes: set[str], edges: list[tuple[str, str]]) -> list[str]:
    """Kahn's algorithm with alphabetical tie-break → a deterministic order."""
    indeg = {n: 0 for n in nodes}
    adj: dict[str, list[str]] = defaultdict(list)
    for a, b in edges:
        adj[a].append(b)
        indeg[b] += 1
    q = [n for n in nodes if indeg[n] == 0]
    heapq.heapify(q)
    order: list[str] = []
    while q:
        n = heapq.heappop(q)
        order.append(n)
        for m in sorted(adj[n]):
            indeg[m] -= 1
            if indeg[m] == 0:
                heapq.heappush(q, m)
    # Any leftover (cycle) appended alphabetically so we never silently drop nodes.
    order += sorted(nodes - set(order))
    return order


def _journey_chains(nodes: list[ServiceNode], edges: list[Edge]) -> dict[str, list[str]]:
    members: dict[str, list[str]] = defaultdict(list)
    for n in nodes:
        for j in n.journeys:
            members[j].append(n.name)
    chains: dict[str, list[str]] = {}
    for j, mem in members.items():
        mset = set(mem)
        sub = [(e.caller, e.callee) for e in edges if e.caller in mset and e.callee in mset]
        chains[j] = _topo_sort(mset, sub)
    return chains


def compile_signals(fragments: list[ServiceSignal]) -> tuple[Topology, ContractSet]:
    nodes = [
        ServiceNode(name=f.service, role=f.role, tier=f.tier, journeys=f.journeys,
                    git_version=f.git_version, owner=f.owner)
        for f in fragments
    ]
    edges = [
        Edge(caller=f.service, callee=d.callee, attribution=d.attribution)
        for f in fragments for d in f.depends_on
    ]
    topo = Topology(version=SIGNAL_VERSION, nodes=nodes, edges=edges,
                    journeys=_journey_chains(nodes, edges))
    contracts = ContractSet(version=SIGNAL_VERSION, contracts=[
        SignalContract(service=f.service, freshness_seconds=f.freshness_seconds,
                       slis=f.slis, supported_decisions=f.supported_decisions,
                       exclusions=f.exclusions, logs=f.logs)
        for f in fragments
    ])
    return topo, contracts


def _dump(model: BaseModel) -> str:
    data = model.model_dump(exclude_defaults=True, exclude_none=True)
    body = yaml.dump(data, sort_keys=False, default_flow_style=False,
                     allow_unicode=True, width=4096)
    return _GENERATED_HEADER + body


def write_compiled(topo: Topology, contracts: ContractSet,
                   out_dir: Path | None = None) -> tuple[Path, Path]:
    d = out_dir or (Path(__file__).parent)
    tp, cp = d / "topology.yaml", d / "contracts.yaml"
    tp.write_text(_dump(topo), encoding="utf-8")
    cp.write_text(_dump(contracts), encoding="utf-8")
    return tp, cp


if __name__ == "__main__":  # pragma: no cover
    frags = load_fragments()
    if not frags:
        print(f"no signal fragments under {_fragments_dir()}")
        raise SystemExit(1)
    topo, contracts = compile_signals(frags)
    tp, cp = write_compiled(topo, contracts)
    print(f"compiled {len(frags)} fragments → {tp.name} ({len(topo.nodes)} nodes, "
          f"{len(topo.edges)} edges, journeys={list(topo.journeys)}) + {cp.name} "
          f"({len(contracts.contracts)} contracts)")
